package com.example.data.remote

import com.example.BuildConfig
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import org.json.JSONArray
import org.json.JSONObject
import java.util.concurrent.TimeUnit

sealed class AiResult {
    data class Success(val outputText: String) : AiResult()
    data class Error(val message: String, val isKeyMissing: Boolean = false) : AiResult()
}

class GeminiService {
    private val client = OkHttpClient.Builder()
        .connectTimeout(45, TimeUnit.SECONDS)
        .readTimeout(45, TimeUnit.SECONDS)
        .writeTimeout(45, TimeUnit.SECONDS)
        .build()

    private val jsonMediaType = "application/json; charset=utf-8".toMediaType()

    suspend fun generateBrandingContent(prompt: String, taskType: String): AiResult = withContext(Dispatchers.IO) {
        val apiKey = BuildConfig.GEMINI_API_KEY
        if (apiKey.isBlank() || apiKey == "MY_GEMINI_API_KEY") {
            return@withContext AiResult.Error(
                message = "Gemini API key is not yet configured in the Secrets panel. Add GEMINI_API_KEY in the Secrets panel to activate live AI generation.",
                isKeyMissing = true
            )
        }

        val systemPrompt = """
            You are "Arafat AI", the official personal branding, copywriting, and marketing assistant for Md. Arafat Sarkar Niloy (Brand name: Freelancer Arafat), a premier Digital Marketing Specialist & Lead Generation Expert based in Bangladesh.
            Your role is to write high-converting, professional, crisp English marketing materials, proposals, case studies, blog outlines, SEO metadata, and client inquiry responses.
            Maintain an authoritative, consultative, confident tone. Never invent fake client figures or unverified metrics. Prioritize clarity, ROI, and actionable strategy.
        """.trimIndent()

        try {
            val rootJson = JSONObject().apply {
                val contentsArray = JSONArray().apply {
                    val contentObj = JSONObject().apply {
                        val partsArray = JSONArray().apply {
                            put(JSONObject().apply { put("text", "Task: $taskType\n\nPrompt/Input:\n$prompt") })
                        }
                        put("parts", partsArray)
                    }
                    put(contentObj)
                }
                put("contents", contentsArray)

                val systemInstructionObj = JSONObject().apply {
                    val sysParts = JSONArray().apply {
                        put(JSONObject().apply { put("text", systemPrompt) })
                    }
                    put("parts", sysParts)
                }
                put("systemInstruction", systemInstructionObj)
            }

            val requestBody = rootJson.toString().toRequestBody(jsonMediaType)
            val request = Request.Builder()
                .url("https://generativelanguage.googleapis.com/v1beta/models/gemini-3.5-flash:generateContent?key=$apiKey")
                .post(requestBody)
                .build()

            val response = client.newCall(request).execute()
            val responseBody = response.body?.string() ?: ""

            if (!response.isSuccessful) {
                val errorMsg = try {
                    val errJson = JSONObject(responseBody)
                    errJson.optJSONObject("error")?.optString("message") ?: "API returned HTTP ${response.code}"
                } catch (e: Exception) {
                    "HTTP ${response.code}: $responseBody"
                }
                return@withContext AiResult.Error(errorMsg)
            }

            val resJson = JSONObject(responseBody)
            val candidates = resJson.optJSONArray("candidates")
            val firstCandidate = candidates?.optJSONObject(0)
            val content = firstCandidate?.optJSONObject("content")
            val parts = content?.optJSONArray("parts")
            val text = parts?.optJSONObject(0)?.optString("text")

            if (!text.isNullOrBlank()) {
                AiResult.Success(text)
            } else {
                AiResult.Error("No response generated by the model.")
            }
        } catch (e: Exception) {
            AiResult.Error("Network error: ${e.localizedMessage ?: "Failed to reach AI service"}")
        }
    }
}
